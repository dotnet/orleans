using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Orleans.Analyzers;
using Xunit;

namespace Analyzers.Tests;

/// <summary>
/// Tests for the analyzer that ensures types marked with [GenerateSerializer] have proper field attributes.
/// In Orleans serialization, each serializable field must be marked with an [Id] attribute to ensure
/// version tolerance and efficient serialization. This analyzer helps developers identify missing
/// field attributes that could cause serialization issues.
/// </summary>
[TestCategory("BVT"), TestCategory("Analyzer")]
[TestSuite("BVT")]
[TestProvider("None")]
[TestArea("Analyzer")]
public class GenerateSerializationAttributesAnalyzerTest : DiagnosticAnalyzerTestBase<GenerateSerializationAttributesAnalyzer>
{
    private async Task VerifyGeneratedDiagnostic(string code)
    {
        var (diagnostics, _) = await GetDiagnosticsAsync(code, new string[0]);

        Assert.NotEmpty(diagnostics);
        Assert.Single(diagnostics);

        var diagnostic = diagnostics.First();
        Assert.Equal(GenerateSerializationAttributesAnalyzer.RuleId, diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
    }

    /// <summary>
    /// Verifies that the analyzer detects when a class with [GenerateSerializer]
    /// has fields without [Id] attributes, which are required for proper Orleans serialization.
    /// </summary>
    [Fact]
    public Task SerializableClass()
        => VerifyGeneratedDiagnostic(@"[GenerateSerializer] public class D { public int f; }");

    /// <summary>
    /// Verifies that the analyzer detects when a struct with [GenerateSerializer]
    /// has fields without [Id] attributes, which are required for proper Orleans serialization.
    /// </summary>
    [Fact]
    public Task SerializableStruct()
        => VerifyGeneratedDiagnostic(@"[GenerateSerializer] public struct D { public int f; }");

    /// <summary>
    /// Verifies that the analyzer detects when a record with [GenerateSerializer]
    /// has fields without [Id] attributes, which are required for proper Orleans serialization.
    /// </summary>
    [Fact]
    public Task SerializableRecord()
        => VerifyGeneratedDiagnostic(@"[GenerateSerializer] public record D { public int f; }");

    /// <summary>
    /// Verifies that the analyzer detects when a record class with [GenerateSerializer]
    /// has fields without [Id] attributes, which are required for proper Orleans serialization.
    /// </summary>
    [Fact]
    public Task SerializableRecordClass()
        => VerifyGeneratedDiagnostic(@"[GenerateSerializer] public record class D { public int f; }");

    /// <summary>
    /// Verifies that the analyzer detects when a record struct with [GenerateSerializer]
    /// has fields without [Id] attributes, which are required for proper Orleans serialization.
    /// </summary>
    [Fact]
    public Task SerializableRecordStruct()
        => VerifyGeneratedDiagnostic(@"[GenerateSerializer] public record struct D { public int f; }");

    /// <summary>
    /// Verifies that types declared in generated code are not reported, since diagnostics cannot be reported there.
    /// </summary>
    [Fact]
    public async Task SerializableClassInGeneratedCode_ShouldNotTriggerDiagnostic()
    {
        var diagnostics = await GetDiagnosticsFullSourceAsync(
            """
            // <auto-generated/>
            using Orleans;

            [GenerateSerializer]
            public class D
            {
                public int f;
            }
            """);

        Assert.Empty(diagnostics);
    }

    [Fact]
    public Task UserDefinedIdAttribute_ShouldTriggerDiagnostic()
        => VerifyGeneratedDiagnostic(
            """
            namespace Custom
            {
                public sealed class IdAttribute : System.Attribute
                {
                    public IdAttribute(uint id)
                    {
                    }
                }
            }

            [GenerateSerializer]
            public class D
            {
                [Custom.Id(0)] public int F;
            }
            """);

    [Theory]
    [InlineData("class", "GenerateSerializer", "GenerateFieldIds.PublicProperties")]
    [InlineData("struct", "GenerateSerializer", "FieldIds.PublicProperties")]
    [InlineData("record", "Serializer", "GenerateFieldIds.PublicProperties")]
    [InlineData("record struct", "global::Orleans.GenerateSerializer", "global::Orleans.GenerateFieldIds.PublicProperties")]
    public async Task PublicProperties_WithExistingMemberAttributes_ShouldNotTriggerDiagnostic(string declarationKind, string attributeName, string fieldIdOption)
    {
        var source = $$"""
            using Orleans;
            using Serializer = Orleans.GenerateSerializerAttribute;
            using FieldIds = Orleans.GenerateFieldIds;

            [{{attributeName}}(GenerateFieldIds = {{fieldIdOption}})]
            public {{declarationKind}} D
            {
                [Id(9)] public int Tagged { get; set; }
                [System.NonSerialized] public int Ignored;
                public int Untagged { get; set; }
                public int UntaggedField;
            }
            """;

        var diagnostics = await GetDiagnosticsFullSourceAsync(source);

        Assert.Empty(diagnostics);
    }

    [Theory]
    [InlineData("GenerateSerializer", "")]
    [InlineData("Serializer", "(GenerateFieldIds = GenerateFieldIds.None)")]
    [InlineData("global::Orleans.GenerateSerializer", "")]
    [InlineData("GenerateSerializer", "(GenerateFieldIds = PublicProperties)")]
    [InlineData("GenerateSerializer", "(GenerateFieldIds = Options.Automatic)")]
    public async Task FieldIdOptionSyntax_ShouldPreserveDiagnosticAttributeLocation(string attributeName, string arguments)
    {
        // Preserve the existing syntax-only interpretation of imported enum members and constants.
        var attribute = attributeName + arguments;
        var source = $$"""
            using Orleans;
            using Serializer = Orleans.GenerateSerializerAttribute;
            using static Orleans.GenerateFieldIds;

            public static class Options
            {
                public const GenerateFieldIds Automatic = GenerateFieldIds.PublicProperties;
            }

            [{{attribute}}]
            public class D
            {
                [Id(0)] public int Tagged { get; set; }
                public int Untagged { get; set; }
            }
            """;

        var diagnostics = await GetDiagnosticsFullSourceAsync(source);

        var diagnostic = Assert.Single(diagnostics);
        Assert.Equal(GenerateSerializationAttributesAnalyzer.RuleId, diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
        Assert.Equal(new TextSpan(source.IndexOf("[" + attribute + "]", StringComparison.Ordinal) + 1, attribute.Length), diagnostic.Location.SourceSpan);
    }

    [Fact]
    public async Task PartialTypes_ShouldAnalyzeOnlyMembersInAttributedDeclaration()
    {
        const string reportedAttribute = "GenerateSerializer(GenerateFieldIds = GenerateFieldIds.None)";
        var source = $$"""
            using Orleans;

            [GenerateSerializer]
            public partial class AnnotatedHere
            {
                [Id(0)] public int Tagged;
            }

            public partial class AnnotatedHere
            {
                public int Untagged;
            }

            [{{reportedAttribute}}]
            public partial class UnannotatedHere
            {
                public int Untagged;
            }

            public partial class UnannotatedHere
            {
                [Id(0)] public int Tagged;
            }

            [GenerateSerializer(GenerateFieldIds = GenerateFieldIds.PublicProperties)]
            public partial class Automatic
            {
                public int Untagged { get; set; }
            }

            public partial class Automatic
            {
                public int Other { get; set; }
            }
            """;

        var diagnostics = await GetDiagnosticsFullSourceAsync(source);

        var diagnostic = Assert.Single(diagnostics);
        Assert.Equal(GenerateSerializationAttributesAnalyzer.RuleId, diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
        Assert.Equal(new TextSpan(source.IndexOf(reportedAttribute, StringComparison.Ordinal), reportedAttribute.Length), diagnostic.Location.SourceSpan);
    }
}
