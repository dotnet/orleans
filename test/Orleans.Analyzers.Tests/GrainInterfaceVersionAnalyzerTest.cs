    private static (CodeFixContext Context, List<CodeAction> Actions) CreateCodeFixContext(
        string diagnosticId,
        ImmutableDictionary<string, string?> properties,
        string source = "public class TestClass { }",
        string? contractsFileContent = null)
    {
        var project = CreateProjectWithAdditionalFilesForCodeFix(source, contractsFileContent);
        var document = Assert.Single(project.Documents);
        var descriptor = new DiagnosticDescriptor(
            diagnosticId,
            "Test diagnostic",
            "Test diagnostic",
            "Test",
            DiagnosticSeverity.Warning,
            isEnabledByDefault: true);
        var diagnostic = Diagnostic.Create(descriptor, Location.None, properties);
        var actions = new List<CodeAction>();
        var context = new CodeFixContext(
            document,
            diagnostic,
            (action, _) => actions.Add(action),
            TestContext.Current.CancellationToken);

        return (context, actions);
    }

