    private async Task<(Solution ChangedSolution, DocumentId? AdditionalDocumentId)> ApplyCodeFixAsync(
        string source,
        string? grainInterfacesFileContent,
        string expectedDiagnosticId,
        string? codeActionTitle = null,
        string? configuredContractsPath = null,
        string? generatedSource = null)
    {
        var project = CreateProjectWithAdditionalFilesForCodeFix(
            source,
            grainInterfacesFileContent,
            configuredContractsPath,
            generatedSource);
        var document = project.Documents.First();
        var compilation = await project.GetCompilationAsync();

        Assert.NotNull(compilation);
        var errors = compilation!.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error);
        Assert.Empty(errors);

        var analyzer = new GrainInterfaceVersionAnalyzer();

        // Build analyzer options with additional files
        var additionalFiles = grainInterfacesFileContent is not null
            ? ImmutableArray.Create<AdditionalText>(new TestAdditionalText(OrleansContractsFileName, grainInterfacesFileContent))
            : ImmutableArray<AdditionalText>.Empty;

        var analyzerOptions = CreateAnalyzerOptions(additionalFiles, analyzerEnabled: true);

        var compilationWithAnalyzers = compilation
            .WithOptions(compilation.Options.WithSpecificDiagnosticOptions(
                analyzer.SupportedDiagnostics.ToDictionary(d => d.Id, d => ReportDiagnostic.Default)))
            .WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(analyzer), analyzerOptions);

        var diagnostics = await compilationWithAnalyzers.GetAnalyzerDiagnosticsAsync();
        var diagnostic = diagnostics.FirstOrDefault(d => d.Id == expectedDiagnosticId);

        Assert.NotNull(diagnostic);

        // Apply code fix
        var codeFixer = new GrainInterfaceVersionCodeFix();
        var actions = new List<CodeAction>();
        var context = new CodeFixContext(
            document,
            diagnostic!,
            (action, _) => actions.Add(action),
            CancellationToken.None);

        await codeFixer.RegisterCodeFixesAsync(context);
        Assert.NotEmpty(actions);

        var action = codeActionTitle is null
            ? actions.FirstOrDefault(candidate => !string.Equals(candidate.Title, RegenerateCodeActionTitle, StringComparison.Ordinal))
                ?? actions.First()
            : actions.Single(candidate => string.Equals(candidate.Title, codeActionTitle, StringComparison.Ordinal));
        var operations = await action.GetOperationsAsync(CancellationToken.None);
        var changedSolution = operations.OfType<ApplyChangesOperation>().Single().ChangedSolution;

        var additionalDocumentId = changedSolution.GetProject(project.Id)?.AdditionalDocumentIds.FirstOrDefault();

        return (changedSolution, additionalDocumentId);
    }

    private async Task<string> ApplyCodeFixAndGetContractsAsync(
        string source,
        string contractsFileContent,
        string expectedDiagnosticId)
    {
        var (changedSolution, additionalDocumentId) = await ApplyCodeFixAsync(source, contractsFileContent, expectedDiagnosticId);
        Assert.NotNull(additionalDocumentId);

        var changedDocument = changedSolution.GetAdditionalDocument(additionalDocumentId!);
        Assert.NotNull(changedDocument);

        return (await changedDocument!.GetTextAsync(TestContext.Current.CancellationToken)).ToString();
    }

    private static void AssertContainsGeneratedMethod(
        string content,
        string clrSignature,
        string contractSignatureSuffix)
    {
        var parameterListStart = clrSignature.IndexOf('(');
        var methodStart = clrSignature.LastIndexOf('.', parameterListStart - 1) + 1;
        var methodName = clrSignature.Substring(methodStart, parameterListStart - methodStart);
        var genericStart = methodName.IndexOf('<');
        if (genericStart >= 0)
        {
            var genericEnd = methodName.LastIndexOf('>');
            var arity = 1;
            for (var index = genericStart + 1; index < genericEnd; index++)
            {
                if (methodName[index] == ',')
                {
                    arity++;
                }
            }

            methodName = $"{methodName.Substring(0, genericStart)}`{arity}";
            var suffixArityEnd = contractSignatureSuffix.IndexOf('(');
            if (contractSignatureSuffix.StartsWith("`", StringComparison.Ordinal)
                && suffixArityEnd >= 0)
            {
                contractSignatureSuffix = contractSignatureSuffix.Substring(suffixArityEnd);
            }
        }

        var pattern =
            $"(?m)^  [0-9A-F]{{8}}: {Regex.Escape(methodName + contractSignatureSuffix)}\\r?$";
        Assert.Matches(pattern, content);
    }

    private static void AssertDiagnosticIds(IEnumerable<Diagnostic> diagnostics, params string[] expected)
        => Assert.Equal(
            expected.OrderBy(id => id, StringComparer.Ordinal),
            diagnostics.Select(diagnostic => diagnostic.Id).OrderBy(id => id, StringComparer.Ordinal));

    private static Project CreateProjectWithAdditionalFilesForCodeFix(
        string source,
        string? grainInterfacesFileContent,
        string? configuredContractsPath = null,
        string? generatedSource = null)
    {
        const string fileName = "Test.cs";

        // Prepend usings
        var sb = new StringBuilder();
        foreach (var @using in Usings)
        {
            sb.AppendLine($"using {@using};");
        }
        sb.AppendLine(source);
        var fullSource = sb.ToString();

        var projectId = ProjectId.CreateNewId(debugName: "TestProject");
        var documentId = DocumentId.CreateNewId(projectId, fileName);

        var assemblies = new[]
        {
            typeof(Task).Assembly,
            typeof(Orleans.IGrain).Assembly,
            typeof(Orleans.Grain).Assembly,
            typeof(Attribute).Assembly,
            typeof(int).Assembly,
            typeof(object).Assembly,
        };

        var metadataReferences = assemblies
            .SelectMany(x => x.GetReferencedAssemblies().Select(Assembly.Load))
            .Concat(assemblies)
            .Distinct()
            .Select(x => MetadataReference.CreateFromFile(x.Location))
            .Cast<MetadataReference>()
            .ToList();

        var assemblyPath = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        metadataReferences.Add(MetadataReference.CreateFromFile(Path.Combine(assemblyPath, "mscorlib.dll")));
        metadataReferences.Add(MetadataReference.CreateFromFile(Path.Combine(assemblyPath, "System.dll")));
        metadataReferences.Add(MetadataReference.CreateFromFile(Path.Combine(assemblyPath, "System.Core.dll")));
        metadataReferences.Add(MetadataReference.CreateFromFile(Path.Combine(assemblyPath, "System.Runtime.dll")));

        var solution = new AdhocWorkspace()
            .CurrentSolution
            .AddProject(projectId, "TestProject", "TestProject", LanguageNames.CSharp)
            .AddMetadataReferences(projectId, metadataReferences)
            .AddDocument(documentId, fileName, SourceText.From(fullSource));

        if (generatedSource is not null)
        {
            solution = solution.AddDocument(
                DocumentId.CreateNewId(projectId, "Generated.g.cs"),
                "Generated.g.cs",
                SourceText.From(generatedSource),
                filePath: "Generated.g.cs");
        }

        // Add additional document if content is provided
        if (grainInterfacesFileContent is not null)
        {
            var contractsDocumentPath = configuredContractsPath is null
                ? OrleansContractsFileName
                : configuredContractsPath.Replace('/', Path.DirectorySeparatorChar);
            var contractsDocumentName = Path.GetFileName(contractsDocumentPath);
            var additionalDocumentId = DocumentId.CreateNewId(projectId, contractsDocumentName);
            solution = solution.AddAdditionalDocument(
                additionalDocumentId,
                contractsDocumentName,
                SourceText.From(grainInterfacesFileContent),
                filePath: contractsDocumentPath);
        }

        if (configuredContractsPath is not null)
        {
            var analyzerConfigDirectory = Path.GetDirectoryName(configuredContractsPath);
            var analyzerConfigPath = string.IsNullOrEmpty(analyzerConfigDirectory)
