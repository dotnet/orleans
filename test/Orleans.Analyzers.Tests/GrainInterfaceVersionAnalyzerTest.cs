    [Fact]
    public async Task CodeFix_PreservesCrLfLineEndingsAndUpdatesVersion()
    {
        const string source = @"
[Version(2)]
public interface IMyGrain : IGrain
{
    Task DoSomething();
}
";
        const string contractsFile = "# OrleansContracts.txt\r\nIMyGrain [Version(1)]\r\n41F3F487: DoSomething() -> Task\r\n";
        var expectedContractsFile =
            GeneratedHeader.Replace("\n", "\r\n", StringComparison.Ordinal) +
            "interface IMyGrain [Version(2)]\r\n" +
            "  41F3F487: DoSomething() -> Task\r\n";
        var properties = ImmutableDictionary<string, string?>.Empty
            .Add("InterfaceName", "IMyGrain")
            .Add("ActualVersion", "2");
        var (context, actions) = CreateCodeFixContext(
            GrainInterfaceVersionAnalyzer.RuleId0017,
            properties,
            source,
            contractsFile);
        var codeFixer = new GrainInterfaceVersionCodeFix();

        await codeFixer.RegisterCodeFixesAsync(context);
        var action = Assert.Single(
            actions,
            action => !string.Equals(action.Title, RegenerateCodeActionTitle, StringComparison.Ordinal));
        var operations = await action.GetOperationsAsync(TestContext.Current.CancellationToken);
        var changedSolution = Assert.Single(operations.OfType<ApplyChangesOperation>()).ChangedSolution;
        var changedProject = changedSolution.GetProject(context.Document.Project.Id);
        Assert.NotNull(changedProject);
        var additionalDocumentId = Assert.Single(changedProject!.AdditionalDocumentIds);
        var changedDocument = changedSolution.GetAdditionalDocument(additionalDocumentId);
        Assert.NotNull(changedDocument);
        var changedText = await changedDocument!.GetTextAsync(TestContext.Current.CancellationToken);
        var actualContractsFile = changedText.ToString();

        Assert.Equal(expectedContractsFile, actualContractsFile);
        Assert.DoesNotContain("\n", actualContractsFile.Replace("\r\n", string.Empty, StringComparison.Ordinal));
        Assert.Empty(changedText.Encoding?.GetPreamble() ?? []);
    }

